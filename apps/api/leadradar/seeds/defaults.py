NAMED = {"key": "name", "op": "exists"}


def c(key: str, value: str | list[str] | None = None, op: str | None = None) -> dict:
    if op == "exists" or value is None:
        return {"key": key, "op": "exists"}
    if isinstance(value, list):
        return {"key": key, "op": "in", "value": value}
    return {"key": key, "op": op or "eq", "value": value}


